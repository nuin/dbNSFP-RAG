"""Markdown sections for a variant inspector report."""

from __future__ import annotations

import json

from inspector_sources import Variant, fetch_myvariant, fetch_variantvalidator

SECTION_TITLES = (
    "Identity",
    "Frequencies (gnomAD)",
    "Predictors",
    "Splice & conservation",
    "Clinical assertions (ClinVar)",
    "Our pipeline classification",
    "Cross-references",
    "Reference context",
    "Notes",
)


def render_section(title: str, lines: list[str]) -> str:
    body = "\n".join(lines).strip()
    if not body:
        return ""
    return f"## {title}\n\n{body}\n"


def render_variant(v: Variant, sections: dict[str, list[str]]) -> str:
    """Compose the multi-section Markdown report."""
    out = [f"# Variant report — {v.gene or 'unknown'} {v.hgvs_c or v.key()}"]
    out.append(
        "\n*Generated by `inspect_variant.py`. Sources cascading: local cache → public APIs.*\n"
    )
    for title in SECTION_TITLES:
        s = render_section(title, sections.get(title, []))
        if s:
            out.append(s)
    return "\n".join(out)


def kv(label: str, value, fmt=str) -> str:
    if value is None or value == "":
        return f"- **{label}**: —"
    try:
        return f"- **{label}**: {fmt(value)}"
    except (TypeError, ValueError, OverflowError):
        return f"- **{label}**: {value}"


