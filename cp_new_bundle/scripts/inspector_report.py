def add_classifications(classifications: list[dict], sections: dict) -> None:
    if classifications:
        for c in classifications:
            sections["Our pipeline classification"].append(
                f"- **{c['classification']}** "
                f"(source: `{c.get('source', '')}`, vv_status: `{c.get('vv_status', '')}`)\n"
                f"    - transcript: {c.get('transcript', '')}\n"
                f"    - c.: {c.get('hgvs_c', '')}\n"
            )
    else:
        sections["Our pipeline classification"].append(
            "- *No matching classification in `cp_new_seqnext_FINAL.tsv`.*"
        )


def add_external_annotations(v: Variant, classifications: list[dict], sections: dict) -> None:
    # --- EXTERNAL: myvariant.info (cross-source aggregator) ---
    mv = fetch_myvariant(v)
    if mv:
        dbsnp = mv.get("dbsnp")
        rsid = dbsnp.get("rsid") if isinstance(dbsnp, dict) else None
        sections["Cross-references"].append(kv("dbSNP rsID", rsid))
        for src in [
            "cosmic",
            "clinvar",
            "dbsnp",
            "evs",
            "exac",
            "gnomad_exome",
            "gnomad_genome",
        ]:
            if src in mv:
                sections["Cross-references"].append(
                    f"- **myvariant.{src}**: present (run `--raw-mv` to see full JSON)"
                )
        mv_clinvar = mv.get("clinvar")
        if mv_clinvar:
            sections["Clinical assertions (ClinVar)"].append(
                f"- myvariant.info ClinVar: {json.dumps(mv_clinvar)[:300]}..."
            )

    # --- EXTERNAL: VariantValidator on the BED transcript ---
    if v.gene and v.chr_hg19 and v.pos_hg19:
        # Try to figure out BED transcript from FINAL file
        bed_tx = next(
            (c["transcript"] for c in classifications if c.get("transcript", "").startswith("NM_")),
            None,
        )
        if bed_tx:
            vv = fetch_variantvalidator(v, transcript=bed_tx)
            if vv:
                keys_with_c = [k for k in vv if ":c." in k]
                for k in keys_with_c[:3]:
                    sections["Identity"].append(f"- **VV resolved**: `{k}`")
